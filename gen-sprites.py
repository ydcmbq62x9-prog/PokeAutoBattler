"""Turn the sprite folder into an embedded SPRITES map.

Each image is cropped to its actual artwork (the Gen 1 sprites sit in a big
transparent box, so uncropped a Pidgey renders a third the size of a Snorlax),
padded back to square so every card matches, and inlined as a data URI — the
published artifact blocks external images, so they have to travel with the file.
"""
import base64, glob, io, json, os, pathlib, sys
from PIL import Image

SRC = '/mnt/user-data/uploads/Sprites'
OUT = pathlib.Path('sprites.js')

# file stem -> game id, for the ones that don't match exactly
ALIASES = {
    'hp-up': 'hpup', 'rare-candy': 'candy', 'exp-share': 'expshare',
    'thunder-stone': 'thunderstone', 'fire-stone': 'firestone',
    'water-stone': 'waterstone', 'leaf-stone': 'leafstone', 'x-attack': 'xattack', 'x-speed': 'xspeed',
    # held items — drop any of these PNGs in and the emoji placeholder retires
    'muscle-band': 'band', 'quick-claw': 'claw', 'eviolite': 'evio',
    'assault-vest': 'coat', 'metal-coat': 'metalcoat', 'charcoal': 'char', 'leftovers': 'lefto',
    'sitrus-berry': 'sitrus', 'focus-band': 'focus', 'lucky-egg': 'egg',
    'amulet-coin': 'coin', 'expert-belt': 'char', 'moon-stone': 'moonstone',
    # v51 trade-off items (drawn icons live in extra-sprites/ until real ones are uploaded)
    'choice-band': 'choice', 'life-orb': 'orb', 'iron-ball': 'iron', 'heart-scale': 'scale',
    'shell-bell': 'bell', 'rocky-helmet': 'helmet',
    # trainers: keyed by boss id so the UI finds them next to the pokémon
    # 3.8.0 roster: the spellings a sprite file might come in
    'nidoran-f': 'nidoranf', 'nidoran_f': 'nidoranf', 'nidoran-female': 'nidoranf', 'nidoran♀': 'nidoranf', 'nidoran-w': 'nidoranf',
    'nidoran-m': 'nidoranm', 'nidoran_m': 'nidoranm', 'nidoran-male': 'nidoranm', 'nidoran♂': 'nidoranm',
    "farfetch'd": 'farfetchd', 'farfetch-d': 'farfetchd', 'farfetch_d': 'farfetchd', 'farfetchd': 'farfetchd',
    # 4.0.0 Gen 2 pack
    'sun-stone': 'sunstone', 'kings-rock': 'kingsrock', 'dragon-scale': 'dragonscale',
    'ltsurge': 'surge', 'lt-surge': 'surge', 'blue-champion': 'blue', 'professor-oak': 'oak', 'blue-rival': 'rival',
}

def process(path):
    im = Image.open(path).convert('RGBA')
    bbox = im.getbbox()                      # crop away the empty margin
    if bbox:
        im = im.crop(bbox)
    w, h = im.size
    side = max(w, h)
    sq = Image.new('RGBA', (side, side), (0, 0, 0, 0))
    sq.alpha_composite(im, ((side - w) // 2, (side - h) // 2))
    if side > 96:                            # they display at 30-52px
        sq = sq.resize((96, 96), Image.NEAREST)
    buf = io.BytesIO()
    sq.save(buf, format='PNG', optimize=True)
    return buf.getvalue(), sq.size

def main():
    files = sorted(glob.glob(os.path.join(SRC, '*.png')))
    # v51: our own drawn icons fill in anything the uploaded folder doesn't have
    have = {pathlib.Path(f).stem.lower() for f in files}
    files += sorted(f for f in glob.glob(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'extra-sprites', '*.png'))
                    if not pathlib.Path(f).stem.startswith('_') and pathlib.Path(f).stem.lower() not in have)
    if not files:
        sys.exit('no sprites found in ' + SRC)
    out, raw_total, enc_total = {}, 0, 0
    for f in files:
        stem = pathlib.Path(f).stem.lower()
        key = ALIASES.get(stem, stem)
        data, size = process(f)
        raw_total += os.path.getsize(f)
        enc_total += len(data)
        out[key] = 'data:image/png;base64,' + base64.b64encode(data).decode()
    # 4.0.0: the same person under a second id (Koga of the Elite Four)
    for new, old in {'koga2': 'koga', 'bruno2': 'bruno', 'lance2': 'lance'}.items():
        if old in out and new not in out: out[new] = out[old]
    body = ',\n'.join('  %s: "%s"' % (json.dumps(k), v) for k, v in sorted(out.items()))
    OUT.write_text(
        '/* ---- SPRITES (generated by gen-sprites.py from the Sprites folder) ----\n'
        '   Each image is cropped to its artwork, squared, and inlined as a data URI.\n'
        '   Re-run the generator after changing any file; anything missing here just\n'
        '   falls back to the coloured letter placeholder. ------------------------ */\n'
        'const SPRITES = {\n' + body + '\n};\n')
    print('%d sprites  ·  %.0f KB source  ->  %.0f KB png  ->  %.0f KB inlined'
          % (len(out), raw_total/1024, enc_total/1024, OUT.stat().st_size/1024))
    return out

if __name__ == '__main__':
    main()
